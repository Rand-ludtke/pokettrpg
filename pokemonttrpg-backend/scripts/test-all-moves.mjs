/**
 * test-all-moves.mjs — Phase 4 of MOVE_AUDIT_CHECKLIST.md
 *
 * A) Data sweep: every move in dist/data/moves.js must be battle-viable
 *    (valid category/target/basePower, no uninterpreted convention fields).
 * B) Real-engine battles: one battle per mechanics class, asserting observed
 *    events match the move's description. Includes every user-reported move.
 *
 * Run: node scripts/test-all-moves.mjs
 */
import path from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const { SyncPSEngine } = require('../dist/sync-ps-engine.js');
const generatedMoves = require('../dist/data/moves.js').default;

const SEED = [7, 13, 29, 51];
let pass = 0, fail = 0;
function check(label, ok) { if (ok) { pass++; } else { fail++; console.log('  FAIL: ' + label); } return ok; }

function mon(overrides) {
    return { name: 'Mon', species: 'Snorlax', level: 50, ability: 'Immunity', item: '', nature: 'Hardy', gender: 'M', shiny: false, evs: {}, ivs: {}, moves: [], ...overrides };
}
const move = (actor, pokemonId, moveId, extra = {}) => ({ type: 'move', actorPlayerId: actor, playerId: actor, pokemonId, moveId, ...extra });

async function runBattle({ p1Team, p2Team, script }) {
    const engine = new SyncPSEngine({ seed: SEED, format: 'gen9customgame' });
    const players = [
        { id: 'p1', name: 'TesterOne', team: p1Team, activeIndex: 0 },
        { id: 'p2', name: 'TesterTwo', team: p2Team, activeIndex: 0 },
    ];
    await engine.initializeBattle(players, { seed: SEED, autoTeamPreview: true });
    const allEvents = [];
    let cursor = (engine.getState().log || []).length;
    for (const actions of script) {
        engine.processTurn(actions);
        const log = engine.getState().log || [];
        allEvents.push(...log.slice(cursor));
        cursor = log.length;
    }
    return allEvents;
}

// ---------- Part A: data sweep over all generated moves ----------
console.log('=== Part A: data sweep (all ' + Object.keys(generatedMoves).length + ' moves) ===');
const VALID_CATEGORIES = new Set(['Physical', 'Special', 'Status']);
const LEFTOVER_FIELDS = ['custom', 'hazard', 'weather', 'terrain', 'critRatio', 'chargeMove', 'newType', 'weightPower'];
let sweepFail = 0;
for (const [id, m] of Object.entries(generatedMoves)) {
    // Only SS2 entries are generated by us; canonical entries legitimately use
    // real Showdown fields like critRatio (Aeroblast) / weather (Hail) / terrain.
    if (m.isNonstandard !== 'Custom') continue;
    const problems = [];
    if (!VALID_CATEGORIES.has(m.category)) problems.push('bad category ' + m.category);
    if (typeof m.basePower !== 'number') problems.push('bad basePower');
    if (!m.target) problems.push('missing target');
    for (const f of LEFTOVER_FIELDS) if (m[f] !== undefined) problems.push('leftover field ' + f);
    if (problems.length) { sweepFail++; if (sweepFail <= 15) console.log('  BAD ' + id + ': ' + problems.join(', ')); }
}
check('A: all moves battle-viable (no leftovers, valid fields)', sweepFail === 0);
check('A: macabredance has boosts {spa:1,spe:1} targeting self', (() => {
    const m = generatedMoves['macabredance'];
    return m && m.target === 'self' && m.boosts && m.boosts.spa === 1 && m.boosts.spe === 1;
})());

// ---------- Part B: real-engine class battles ----------
const p1Snorlax = (moves) => [mon({ species: 'Snorlax', level: 55, moves, ability: 'Thick Fat', evs: { hp: 252 } })];
const p2Snorlax = (moves) => [mon({ species: 'Snorlax', level: 55, moves, ability: 'Thick Fat', evs: { hp: 252 } })];

console.log('=== Part B: real-engine class battles ===');
{ // 1. Macabre Dance — the user-reported bug
    const ev = await runBattle({ p1Team: p1Snorlax(['macabredance']), p2Team: p2Snorlax(['tackle']), script: [[move('p1', 'p1a', 'macabredance'), move('p2', 'p2a', 'tackle')]] });
    const boost = ev.filter((l) => l.startsWith('|-boost|p1a'));
    check('B1: Macabre Dance raises Sp.Atk and Speed (|-boost| spa & spe)', boost.some((l) => /\|spa\|/.test(l)) && boost.some((l) => /\|spe\|/.test(l)));
    check('B1: Macabre Dance is a Status move (no damage dealt)', !ev.some((l) => l.startsWith('|-damage|p2a')));
}
{ // 2. Dragonfly Charge — +2 priority then recoil
    const ev = await runBattle({ p1Team: [mon({ species: 'Snorlax', level: 55, moves: ['dragonflycharge'], ability: 'Thick Fat', evs: { hp: 252 } })], p2Team: p2Snorlax(['bulldoze']), script: [[move('p1', 'p1a', 'dragonflycharge'), move('p2', 'p2a', 'bulldoze')]] });
    const movesOrder = ev.filter((l) => l.startsWith('|move|')).map((l) => (l.includes('|p1a:') ? 'p1' : 'p2'));
    check('B2: Dragonfly Charge strikes first (+2 priority)', movesOrder[0] === 'p1');
    check('B2: Dragonfly Charge recoil applied ([from] Recoil)', ev.some((l) => l.startsWith('|-damage|') && /\[from\] Recoil/.test(l)) || ev.some((l) => l.startsWith('|-recoil|')));
}
{ // 3. Gossip — lowers target Sp.Atk & Sp.Def
    const ev = await runBattle({ p1Team: p1Snorlax(['gossip']), p2Team: p2Snorlax(['tackle']), script: [[move('p1', 'p1a', 'gossip'), move('p2', 'p2a', 'tackle')]] });
    // Showdown emits stat drops as |-unboost| with positive magnitude
    // (e.g. "|-unboost|p2a|spa|1"), not as |-boost| with negative values.
    const unboost = ev.filter((l) => l.startsWith('|-unboost|p2a'));
    check('B3: Gossip lowers foe Sp.Atk and Sp.Def', unboost.some((l) => /\|spa\|1/.test(l)) && unboost.some((l) => /\|spd\|1/.test(l)));
}
{ // 4. Gold Rush (Clear Smite clone) — resets target stat changes
    const ev = await runBattle({ p1Team: p1Snorlax(['goldrush']), p2Team: p2Snorlax(['dragondance', 'tackle']), script: [[move('p1', 'p1a', 'tackle'), move('p2', 'p2a', 'dragondance')], [move('p1', 'p1a', 'goldrush'), move('p2', 'p2a', 'tackle')]] });
    check('B4: Gold Rush clears foe stat changes (|-clearboost|p2a)', ev.some((l) => l.startsWith('|-clearboost|p2a')));
}
{ // 5. Nectartap — heals 50%
    const ev = await runBattle({ p1Team: p1Snorlax(['nectartap']), p2Team: p2Snorlax(['bodyslam']), script: [[move('p1', 'p1a', 'nectartap'), move('p2', 'p2a', 'bodyslam')]] });
    check('B5: Nectartap emits |-heal|p1a', ev.some((l) => l.startsWith('|-heal|p1a')));
}
{ // 6. Infection (Hex clone) — damages a statused target
    const ev = await runBattle({ p1Team: [mon({ species: 'Snorlax', level: 55, moves: ['toxic', 'infection'], ability: 'Thick Fat', evs: { hp: 252 } })], p2Team: p2Snorlax(['tackle']), script: [[move('p1', 'p1a', 'toxic'), move('p2', 'p2a', 'tackle')], [move('p1', 'p1a', 'infection'), move('p2', 'p2a', 'tackle')]] });
    check('B6: Infection (Hex clone) damages statused target', ev.some((l) => l.startsWith('|move|p1a') && /Infection/i.test(l)) && ev.some((l) => l.startsWith('|-damage|p2a')));
}
{ // 7. Frozenheart (Heal Bell clone) — cures party status
    const ev = await runBattle({ p1Team: p1Snorlax(['frozenheart']), p2Team: p2Snorlax(['toxic']), script: [[move('p1', 'p1a', 'frozenheart'), move('p2', 'p2a', 'toxic')]] });
    check('B7: Frozenheart executes cleanly as a status move', ev.some((l) => l.startsWith('|move|p1a')) && !ev.some((l) => l.startsWith('|-damage|p2a')));
}
{ // 8. Arctic Parasite — attacking + frostbite chance
    const ev = await runBattle({ p1Team: p1Snorlax(['arcticparasite']), p2Team: p2Snorlax(['tackle']), script: [[move('p1', 'p1a', 'arcticparasite'), move('p2', 'p2a', 'tackle')]] });
    check('B8: Arctic Parasite attacks and deals damage', ev.some((l) => l.startsWith('|move|p1a') && /Arctic Parasite/i.test(l)) && ev.some((l) => l.startsWith('|-damage|p2a')));
}
{ // 9. Magnetforce — attacking + 30% self Sp.Def chance
    const ev = await runBattle({ p1Team: p1Snorlax(['magnetforce']), p2Team: p2Snorlax(['tackle']), script: [[move('p1', 'p1a', 'magnetforce'), move('p2', 'p2a', 'tackle')]] });
    check('B9: Magnetforce attacks and deals damage', ev.some((l) => l.startsWith('|-damage|p2a')));
}
{ // 10. Strafe — strike-first priority
    const ev = await runBattle({ p1Team: p1Snorlax(['strafe']), p2Team: p2Snorlax(['tackle']), script: [[move('p1', 'p1a', 'strafe'), move('p2', 'p2a', 'tackle')]] });
    const movesOrder = ev.filter((l) => l.startsWith('|move|')).map((l) => (l.includes('|p1a:') ? 'p1' : 'p2'));
    check('B10: Strafe (strike-first) moves first', movesOrder[0] === 'p1');
}
{ // 11. Corecollapse — mixed self-boost (def down, atk+spe up)
    const ev = await runBattle({ p1Team: p1Snorlax(['corecollapse']), p2Team: p2Snorlax(['tackle']), script: [[move('p1', 'p1a', 'corecollapse'), move('p2', 'p2a', 'tackle')]] });
    const boosts = ev.filter((l) => l.startsWith('|-boost|p1a') || l.startsWith('|-unboost|p1a'));
    check('B11: Corecollapse lowers def and raises atk+spe', boosts.some((l) => /\|def\|/.test(l)) && boosts.some((l) => /\|atk\|/.test(l)) && boosts.some((l) => /\|spe\|/.test(l)));
}
{ // 12. Lazybreak — puts the foe to sleep
    const ev = await runBattle({ p1Team: p1Snorlax(['lazybreak']), p2Team: p2Snorlax(['tackle']), script: [[move('p1', 'p1a', 'lazybreak'), move('p2', 'p2a', 'tackle')]] });
    check('B12: Lazybreak puts foe to sleep (|-status|p2a|slp)', ev.some((l) => l.startsWith('|-status|p2a') && /slp/.test(l)));
}

