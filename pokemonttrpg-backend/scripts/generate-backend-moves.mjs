/**
 * generate-backend-moves.mjs
 *
 * Generates pokemonttrpg-backend/data/moves.ts from the client-side SS2 moves JSON.
 * This ensures the server-side PS engine has all SS2 moves with proper PP/target/priority/flags/num.
 *
 * Run: node pokemonttrpg-backend/scripts/generate-backend-moves.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const SS2_MOVES_JSON = path.join(__dirname, '..', '..', 'tauri-app', 'public', 'data', 'ss2-patch', 'generated', 'moves.custom.ss2-soulstones.json');
const SS1_MOVES_JSON = path.join(__dirname, '..', '..', 'tauri-app', 'public', 'data', 'soulstones-part1', 'generated', 'moves.custom.soulstones.json');
const OUT_DIR = path.join(__dirname, '..', 'data');
const OUT_FILE = path.join(OUT_DIR, 'moves.ts');

// Load SS2 moves
let ss2Moves = {};
if (fs.existsSync(SS2_MOVES_JSON)) {
  ss2Moves = JSON.parse(fs.readFileSync(SS2_MOVES_JSON, 'utf8'));
  console.log(`Loaded ${Object.keys(ss2Moves).length} SS2 moves`);
} else {
  console.warn(`SS2 moves file not found: ${SS2_MOVES_JSON}`);
}

// Load SS1 moves (if exists)
let ss1Moves = {};
if (fs.existsSync(SS1_MOVES_JSON)) {
  ss1Moves = JSON.parse(fs.readFileSync(SS1_MOVES_JSON, 'utf8'));
  console.log(`Loaded ${Object.keys(ss1Moves).length} SS1 moves`);
} else {
  console.warn(`SS1 moves file not found: ${SS1_MOVES_JSON}`);
}

// Merge moves, ensuring all have battle-critical fields
function normalizeMove(moveId, moveData) {
  const normalized = { ...(moveData || {}) };
  // Ensure pp is a valid number > 0
  if (typeof normalized.pp !== 'number' || !Number.isFinite(normalized.pp) || normalized.pp <= 0) {
    const category = String(normalized.category || 'Status').toLowerCase();
    const bp = Number(normalized.basePower || normalized.power || 0);
    normalized.pp = category === 'status' ? 15 : (bp > 0 ? 20 : 10);
  }
  // Ensure target
  if (!normalized.target) normalized.target = 'normal';
  // Ensure priority
  if (normalized.priority == null) normalized.priority = 0;
  // Ensure flags
  if (!normalized.flags) normalized.flags = {};
  // Ensure num
  if (normalized.num == null) normalized.num = 0;
  return normalized;
}

const allMoves = {};

// Add SS1 moves first (SS2 will override if same key)
for (const [moveId, moveData] of Object.entries(ss1Moves)) {
  allMoves[moveId] = normalizeMove(moveId, moveData);
}

// Add SS2 moves
for (const [moveId, moveData] of Object.entries(ss2Moves)) {
  allMoves[moveId] = normalizeMove(moveId, moveData);
}

console.log(`Total merged moves: ${Object.keys(allMoves).length}`);

// Generate TypeScript file
const tsContent = `/**
 * Auto-generated custom moves for the backend PS engine.
 * Generated by scripts/generate-backend-moves.mjs
 * 
 * Contains SS1 (Soulstones) and SS2 (Soulstones 2) custom moves with
 * proper pp/target/priority/flags/num fields for the PS simulator.
 */

const customMoves: Record<string, any> = ${JSON.stringify(allMoves, null, 2)};

export default customMoves;
`;

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT_FILE, tsContent, 'utf8');
console.log(`Wrote ${OUT_FILE} (${(fs.statSync(OUT_FILE).size / 1024).toFixed(1)} KB)`);